// Split the app into small files for Base44 when one big file is too long to paste.
// Output: transfer/parts/src/components/seams/SeamsP1.jsx … and transfer/parts/src/pages/SeamsAll.jsx (the page).
// Only files reachable from SeamsApp are included; each part imports what it uses from earlier parts.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "fs";
import { transform } from "../node_modules/esbuild/lib/main.js";
const LIMIT = Number(process.argv[2] || 24000);
const fe = new URL("../src/", import.meta.url).pathname;
const out = new URL("../transfer/parts/", import.meta.url).pathname;
const resolve = (from, spec) => {
  const base = spec.startsWith("@/") ? `${fe}${spec.slice(2)}` : new URL(spec, `file://${from}`).pathname;
  for (const c of [base, `${base}.js`, `${base}.jsx`, `${base}/index.js`, `${base}/index.jsx`]) { try { readFileSync(c); return c; } catch {} }
  return null;
};
const importsOf = (f) => [...readFileSync(f, "utf8").matchAll(/^import\s+[^;]*?from\s+"((?:@\/|\.\.?\/)[^"]*)";/gm)].map((m) => m[1]).filter((s) => s !== "@/api/base44Client").map((s) => resolve(f, s)).filter(Boolean);
const order = [], state = new Map();
const visit = (f) => { if (state.has(f)) return; state.set(f, 1); for (const d of importsOf(f)) visit(d); order.push(f); };
visit(`${fe}pages/SeamsApp.jsx`);
const reactNames = new Set(), mods = [], seen = new Map();
for (const f of order) {
  let src = readFileSync(f, "utf8");
  src = src.replace(/^import\s+React\s*,?\s*\{([^}]*)\}\s+from\s+"react";\s*$/gm, (_, n) => { n.split(",").map((x) => x.trim()).filter(Boolean).forEach((x) => reactNames.add(x)); return ""; });
  src = src.replace(/^import\s+React\s+from\s+"react";\s*$/gm, "");
  src = src.replace(/^import\s+\{([^}]*)\}\s+from\s+"react";\s*$/gm, (_, n) => { n.split(",").map((x) => x.trim()).filter(Boolean).forEach((x) => reactNames.add(x)); return ""; });
  src = src.replace(/^import\s+[^;]*from\s+"[^"]*";.*$/gm, "");
  src = src.replace(/^export\s+default\s+(?=function|class|async)/gm, "").replace(/^export\s+(?=const|let|function|class|async)/gm, "");
  src = src.replace(/^export\s+default\s+\w+;?\s*$/gm, "").replace(/^export\s*\{[^}]*\};?\s*$/gm, "");
  const names = [...src.matchAll(/^(?:async\s+)?(?:const|let|var|function\*?|class)\s+(\w+)/gm)].map((m) => m[1]);
  for (const n of names) { if (seen.has(n)) throw new Error(`duplicate top-level name ${n} in ${f} and ${seen.get(n)}`); seen.set(n, f); }
  const code = (await transform(src, { loader: "jsx", jsx: "preserve", minifyWhitespace: true })).code;
  mods.push({ f: f.replace(fe, "src/"), code, names });
}
const parts = [];
for (const m of mods) {
  const last = parts[parts.length - 1];
  if (!last || last.size + m.code.length > LIMIT) parts.push({ mods: [m], size: m.code.length }); else { last.mods.push(m); last.size += m.code.length; }
}
rmSync(out, { recursive: true, force: true });
mkdirSync(`${out}src/components/seams`, { recursive: true }); mkdirSync(`${out}src/pages`, { recursive: true });
const head = `import React, { ${[...reactNames].join(", ")} } from "react";\nimport { base44 } from "@/api/base44Client";\n`;
const exported = [];
parts.forEach((p, i) => {
  const body = p.mods.map((m) => `// ${m.f}\n${m.code}`).join("\n");
  const imports = exported.map(({ part, names }) => {
    const used = names.filter((n) => new RegExp(`\\b${n}\\b`).test(body));
    return used.length ? `import { ${used.join(", ")} } from "@/components/seams/SeamsP${part}";\n` : "";
  }).join("");
  const names = p.mods.flatMap((m) => m.names);
  const isLast = i === parts.length - 1;
  const file = `// Seams part ${i + 1} of ${parts.length}. Generated by npm run parts. Paste unchanged.\n${head}${imports}${body}\nexport { ${names.join(", ")} };\n${isLast ? "export default SeamsApp;\n" : ""}`;
  const path = isLast ? `${out}src/pages/SeamsAll.jsx` : `${out}src/components/seams/SeamsP${i + 1}.jsx`;
  writeFileSync(path, file);
  exported.push({ part: i + 1, names });
  console.log(`${isLast ? "src/pages/SeamsAll.jsx" : `src/components/seams/SeamsP${i + 1}.jsx`}  ${file.length} chars`);
});
